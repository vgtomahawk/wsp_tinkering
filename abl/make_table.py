def get(tag):
    s = json.load(open(R / tag / "scores.json"))
    j = json.load(open(R / tag / "judge.json")) if (R / tag / "judge.json").exists() else {}
    jr = lambda k: j.get(k, {}).get("rate")
    return {"judge_refusal": jr("jbb_harmful_refusal"), "regex_refusal": s["jbb_harmful"]["refusal"],
            "unsafe": jr("jbb_harmful_jailbreak"), "benign": s["jbb_benign"]["refusal"],
            "ae_judge": jr("ae_harmful_refusal"), "ae_over": s["ae_over_refusal"]["refusal"],
            "ml_judge": jr("ae_ml_harmful_refusal"), "kl": s["kl_first_token"], "ce": s["alpaca_ce"]}


def fmt(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "–"
    if len(vals) == 1:
        return f"{vals[0]:.2f}" if vals[0] >= 0.01 or vals[0] == 0 else f"{vals[0]:.3f}"
    return f"{statistics.mean(vals):.2f} ({min(vals):.2f}–{max(vals):.2f})"


cols = [("judge_refusal", "JBB refusal (JBB judge) ↓"), ("regex_refusal", "JBB refusal (regex)"),
        ("unsafe", "JBB unsafe (JBB judge)"), ("benign", "JBB benign refusal"),
        ("ae_judge", "AE harmful refusal (judge)"), ("ae_over", "AE over-refusal"),
        ("ml_judge", "AE multilingual refusal (judge)"), ("kl", "KL ↓"), ("ce", "Alpaca CE")]
lines = ["# Results: abliteration by weight-space programming on Qwen3.5-0.8B\n",
         "Generated by `abl/make_table.py` from each run's `scores.json` and `judge.json`. JBB = JailbreakBench's 100",
         "harmful (and 100 benign) behaviors; AE = treadon/abliteration-eval. Headline: refusal by JailbreakBench's",
         "official refusal-judge prompt (judge model Claude Sonnet 5.5). Regex = Arditi et al.'s 12 refusal phrases.",
         "KL = first-token KL(unedited || edited) on 100 harmless prompts (Heretic / Young 2026 metric). Runs where",
         "the outer model declined or abstained are in `abl/AGENT_BEHAVIOR.md`.\n",
         "| Row | Passes | Arm | " + " | ".join(c[1] for c in cols) + " |",
         "|---|---|---|" + "---|" * len(cols)]
for label, outer, passes, arm, tags in ROWS:
    data = [get(t) for t in tags if (R / t / "scores.json").exists()]
    if not data:
        continue
    lines.append(f"| {label} | {passes} | {arm} | " + " | ".join(fmt([d[k] for d in data]) for k, _ in cols) + " |")
(R / "RESULTS_TABLE.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
